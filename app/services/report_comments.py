def load_level(server, metric):
    if server.status == "offline" or utcnow() - metric.collected_at > timedelta(
        seconds=server.monitoring_interval * 2
    ):
        return "unknown"
    values = {
        "cpu": metric.cpu_usage,
        "ram": metric.ram_percent,
        "swap": metric.swap_percent,
        "disk": metric.disk_percent,
    }
    for resource, value in values.items():
        critical = server.thresholds.get(resource + "_critical")
        if critical is not None and value > critical:
            return "critical"
    if any(value > server.thresholds[resource + "_warning"] for resource, value in values.items()):
        return "warning"
    if any(
        state not in ("active", "unknown") for state in metric.details.get("services", {}).values()
    ):
        return "warning"
    return "normal"


def rotating_comment(server, level):
    if level == "unknown":
        return "Бляяя… Свіжих даних немає. Спочатку відновимо перевірку, потім робитимемо висновки."
    phrases = PHRASES[level]
    key = f"report_comment:{server.id}:{level}"
    initial = secrets.randbelow(len(phrases))
    upsert_setting(key, initial, (Setting.value + 1) % len(phrases))
    index = db.session.scalar(db.select(Setting.value).where(Setting.key == key))
    return phrases[index]


def upsert_setting(key, initial, updated_value):
    if db.engine.dialect.name == "mysql":
        statement = mysql_insert(Setting).values(key=key, value=initial)
        statement = statement.on_duplicate_key_update(value=updated_value)
    else:
        statement = sqlite_insert(Setting).values(key=key, value=initial)
        statement = statement.on_conflict_do_update(
            index_elements=["key"], set_={"value": updated_value}
        )
    db.session.execute(statement)
